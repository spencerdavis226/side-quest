const parse = (): string[] =>
  answers
    .trim()
    .split("\n")
    .map((line) => {
      const [name, words] = line.split(": ") as [string, string];
      const w = words.split(", ");
      return `${name.toUpperCase()}. Don't say ${w.slice(0, -1).join(", ")} or ${w[w.length - 1]}.`;
    });

export const quizAnswers = parse();

/** The answers dealt out across `count` quiz cards, interleaved so each card
 * mixes easy and hard ones and no answer sits on two cards. */
export const quizPools = (count: number): string[][] =>
  Array.from({ length: count }, (_, k) =>
    quizAnswers.filter((_, i) => i % count === k),
  );
