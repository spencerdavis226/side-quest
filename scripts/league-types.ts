// Writes docs/LEAGUE_TYPES.md (generated; never hand-edit it): every League
// starter form and every League fight with its type, from the cards
// themselves (`src/content/league/types.ts` sets them), and how often each
// starter type meets a matchup in a typical run. Run `npm run league:types`
// after changing a League card or a type.
import { writeFileSync } from "node:fs";
import { pokemonCards, pokemonPack } from "../src/content/pokemon";
import { starters } from "../src/content/league/starters";
import { questStages } from "../src/game/engine";
import { matchup } from "../src/game/matchup";
import { pokemonTypes } from "../src/presentation/pokemon-types";
import type { CardDefinition, PokemonType } from "../src/game/types";

const byId = new Map(pokemonCards.map((c) => [c.id, c]));
const stages = questStages(pokemonPack.quest!);
const name = (t: PokemonType | undefined) => (t ? pokemonTypes[t].name : "—");
const cell = (s: string) => s.replaceAll("|", "\\|");
const how = (c: CardDefinition) =>
  c.dice
    ? `${c.dice.count === 1 ? "" : c.dice.count}d${c.dice.sides}`
    : "plaques";
// A hideout is one of nine routes through the run.
const hideout = (label: string) =>
  /Hideout|HQ|Castle|Lab|House|Tower|Base/.test(label);

const lines: string[] = [
  "# League types",
  "",
  "Generated by `npm run league:types` from the cards; never hand-edit. Types are set in `src/content/league/types.ts` (owner, 2026-10-25). A dice fight against a type the starter beats is rolled twice, keeping the better; one that beats the starter keeps the worse. A fight settled with plaques costs 1 HP less or more when lost. A matchup reads both ways: whoever hits the other harder has the edge (`src/game/matchup.ts`).",
  "",
  "## Starters",
  "",
  "| Starter | Type | Later forms |",
  "| --- | --- | --- |",
];
for (const s of starters)
  lines.push(
    `| ${s.title} | ${name(s.type)} | ${(s.evolves ?? [])
      .map((e) => `${e.title}${e.type ? ` (${name(e.type)})` : ""}`)
      .join(", ")} |`,
  );

// Each starter type's matchups in a run, weighted by how often each card is
// dealt.
const starterTypes = [...new Set(starters.map((s) => s.type!))];
lines.push(
  "",
  "## Matchups in a typical run",
  "",
  "Typed fights met per run, weighted by how often each is dealt (about 38 in all), by the starter's type.",
  "",
  "| Starter type | Starters | Super effective | Not very effective |",
  "| --- | --- | --- | --- |",
);
for (const t of starterTypes) {
  let good = 0;
  let bad = 0;
  for (const st of stages) {
    const weight =
      (st.pick / st.cardIds.length) * (hideout(st.label) ? 1 / 9 : 1);
    for (const id of st.cardIds) {
      const c = byId.get(id)!;
      if (!c.battle || !c.type) continue;
      const edge = matchup(t, c.type).edge;
      if (edge === "advantage") good += weight;
      if (edge === "disadvantage") bad += weight;
    }
  }
  lines.push(
    `| ${name(t)} | ${starters.filter((s) => s.type === t).length} | ${good.toFixed(1)} | ${bad.toFixed(1)} |`,
  );
}

lines.push("", "## Fights", "");
const seen = new Set<string>();
for (const st of stages) {
  // A route's Ace Trainers wait behind its crossroads.
  const fights = [...st.cardIds, ...(st.elite ?? [])]
    .map((id) => byId.get(id)!)
    .filter((c) => c.battle && !seen.has(c.id));
  if (!fights.length) continue;
  lines.push(
    `### ${st.label}`,
    "",
    "| Card | Ribbon | Type | Roll | Rules |",
    "| --- | --- | --- | --- | --- |",
  );
  for (const c of fights) {
    seen.add(c.id);
    lines.push(
      `| ${cell(c.title)} | ${cell(c.ribbon ?? "")} | ${c.type === "trio" ? "Fire, Water or Grass: the brother who beats you" : name(c.type)} | ${how(c)} | ${cell(c.rules)} |`,
    );
  }
  lines.push("");
}

writeFileSync("docs/LEAGUE_TYPES.md", lines.join("\n"));
console.log(`Wrote docs/LEAGUE_TYPES.md (${seen.size} fights).`);
